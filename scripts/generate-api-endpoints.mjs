// Regenerates api/endpoints.md and public/openapi.yaml from the accepted public OpenAPI contract.
// Usage: npm run generate:api [-- path/to/openapi.yaml]
// Defaults to the sibling openapi-spec checkout used in the Assign workspace.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"
import { parse, stringify } from "yaml"
import { isInternal, publicContract } from "./public-contract.mjs"
import { approvedAuthoringSource } from "./authoring-contract.mjs"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const args = process.argv.slice(2).filter((arg) => arg !== "--check")
const outputIndex = args.indexOf("--output-root")
const outputRoot = outputIndex === -1 ? root : resolve(args.splice(outputIndex, 2)[1])
// Local source preparation uses an independently approved authoring graph.
// It never supplies release evidence to publicContract or package validation.
const approvalIndex = args.indexOf("--authoring-approval")
const approvalPath = approvalIndex === -1 ? process.env.ASSIGN_DOCS_AUTHORING_APPROVAL : resolve(args.splice(approvalIndex, 2)[1])
const source = resolve(args[0] ?? process.env.ASSIGN_OPENAPI ?? resolve(root, "../openapi-spec/openapi.yaml"))
const input = parse(readFileSync(source, "utf8"))
const manifest = process.env.ASSIGN_PUBLIC_RELEASE_MANIFEST
  ? JSON.parse(readFileSync(process.env.ASSIGN_PUBLIC_RELEASE_MANIFEST, "utf8")) : undefined
const spec = approvalPath ? approvedAuthoringSource(input, approvalPath) : publicContract(input, manifest)
const methods = ["get", "post", "put", "patch", "delete"]

const guides = {
  Authentication: "./authentication",
  Account: "./account",
  Workspaces: "./workspaces",
  Projects: "./projects",
  Tasks: "./tasks",
  Integrations: "./integrations",
  Documents: "./documents",
  Attachments: "./attachments",
  Search: "./search",
  Knowledge: "./knowledge",
  Discuss: "./discuss",
  Agents: "./agents",
  "Time tracking": "../guides/time-tracking",
}

const authLabels = {
  browserSession: "Session",
  bearerToken: "Token",
  developerAccessToken: "CLI",
  nativeAccessToken: "Mobile",
}
const byTag = new Map((spec.tags ?? []).map((tag) => [tag.name, { ...tag, operations: [] }]))
for (const [path, item] of Object.entries(spec.paths ?? {})) {
  for (const method of methods) {
    const operation = item[method]
    if (!operation) continue
    const tag = operation.tags?.[0] ?? "Other"
    if (!byTag.has(tag)) byTag.set(tag, { name: tag, operations: [] })
    const auth = [...new Set((operation.security ?? spec.security ?? []).flatMap((entry) => Object.keys(entry)))]
    if (!approvalPath && isInternal(operation, operation.security ?? spec.security ?? [])) continue
    byTag.get(tag).operations.push({
      method: method.toUpperCase(),
      path,
      summary: operation.summary ?? operation.operationId ?? "",
      deprecated: Boolean(operation.deprecated),
      auth: auth.length ? auth.map((name) => authLabels[name] ?? name).join(", ") : "Public",
    })
  }
}

const escape = (value) => String(value).replaceAll("|", "\\|").replace(/\s+/g, " ").trim()
const total = [...byTag.values()].reduce((sum, tag) => sum + tag.operations.length, 0)
const lines = [
  "---",
  "description: Every public Assign HTTP API operation, grouped by resource, with a download of the OpenAPI document.",
  "outline: 2",
  "---",
  "",
  "<!-- Generated by scripts/generate-api-endpoints.mjs. Do not edit by hand. -->",
  "",
  "# Endpoint index",
  "",
  ...(approvalPath ? ['<Badge type="warning" text="Awaiting deployment" />', ""] : []),
  `${total} operations from the public contract, **${spec.info.title} ${spec.info.version}**. Paths are`,
  "relative to `https://api.assign.so`.",
  "",
  "- **OpenAPI document:** [`openapi.yaml`](/openapi.yaml) (OpenAPI 3.1). Use it to generate a client,",
  "  import into Postman or Insomnia, or browse it in any OpenAPI viewer. It is the",
  "  authoritative source for request and response schemas.",
  "- **Auth:** `Session` browser session, `Token` personal API token, `CLI` developer-client token,",
  "  `Mobile` native token, `Public` no credential. See [Authentication](./authentication).",
  "",
]
for (const tag of byTag.values()) {
  if (!tag.operations.length) continue
  const status = tag["x-assign-status"] === "upcoming" ? ' <Badge type="warning" text="Upcoming" />' : ""
  lines.push(`## ${tag.name}${status}`, "")
  if (tag.description) lines.push(escape(tag.description), "")
  if (guides[tag.name]) lines.push(`Guide: [${tag.name}](${guides[tag.name]})`, "")
  lines.push("| Operation | Summary | Auth |", "| --- | --- | --- |")
  for (const op of tag.operations.sort((a, b) => a.path.localeCompare(b.path) || methods.indexOf(a.method.toLowerCase()) - methods.indexOf(b.method.toLowerCase()))) {
    const summary = op.deprecated ? `${escape(op.summary)} <Badge type="warning" text="Deprecated" />` : escape(op.summary)
    lines.push(`| \`${op.method} ${escape(op.path)}\` | ${summary} | ${escape(op.auth)} |`)
  }
  lines.push("")
}
const outputs = {
  "api/endpoints.md": lines.join("\n"),
  "public/openapi.yaml": stringify(approvalPath ? spec : publicContract(spec), { lineWidth: 0 }),
}
for (const [file, output] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if (readFileSync(resolve(outputRoot, file), "utf8") !== output) throw new Error(`${file} is stale; run npm run generate:api`)
  } else {
    mkdirSync(dirname(resolve(outputRoot, file)), { recursive: true })
    writeFileSync(resolve(outputRoot, file), output)
  }
}
console.log(`${process.argv.includes("--check") ? "Checked" : "Generated"} ${total} public operations`)
